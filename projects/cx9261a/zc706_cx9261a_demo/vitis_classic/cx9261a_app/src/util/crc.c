/**
 * @brief	CRC8 compare cheker
 *
 * @param   buffPtr	data buffer pointer.
 * @param   dataLen	data length
 * @param	crcOffset	byte offset of crc stored position.
 * @param	poly	polynomials of crc
 *
 * @return	true
 * 			false
 *
 ******************************************************************************/
bool crc8_check(uint8_t *buffPtr, uint32_t dataLen, uint32_t crcOffset, uint16_t poly)
{
	int Status = SUCCESS;
	uint8_t crc_comp;
	uint8_t crc;
	if (dataLen == 0)
	{
		return false;
	}
	crc_comp = (uint8_t)(*(buffPtr + crcOffset));
	Status = crc8_gen(buffPtr, dataLen, poly, &crc);
	if (Status == SUCCESS)
	{
		if (crc == crc_comp)
		{
			return true;
		}
		else
		{
			return false;
		}
	}
	else
	{
		return false;
	}
}

