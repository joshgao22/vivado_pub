/**
 * @brief	CRC8 generator
 *
 * @param   buffPtr	data buffer pointer.
 * @param   dataLen	data length
 * @param	poly	polynomials of crc
 * @param	crcVal	a pointer to store generated crc value
 *
 * @return  SUCCESS
 * 			FAILURE
 *
 ******************************************************************************/
int crc8_gen(uint8_t *buffPtr, uint32_t dataLen, uint16_t poly, uint8_t *crcVal)
{
	uint8_t crc = CRC8_INIT;
	const uint8_t *crc_lut = NULL;

	switch (poly)
	{
#ifdef __CRC_LSB
	case 0x31:
		crc_lut = crc8_31_lsb_lut;
		break;
	default:
		return FAILURE;
#else
	case 0x31:
		crc_lut = crc8_31_msb_lut;
		break;
	default:
		return FAILURE;
#endif
	}

	for (int i = 0; i < dataLen; i++)
	{
		crc = crc_lut[(uint8_t)(crc ^ buffPtr[i])];
	}
	*crcVal = crc;
	return SUCCESS;
}

/*****************************************************************************/
/**
 * @brief	CRC16 generator
 *
 * @param   buffPtr	data buffer pointer.
 * @param   dataLen	data length
 * @param	poly	polynomials of crc
 * @param	crcVal	a pointer to store generated crc value
 *
 * @return  SUCCESS
 * 			FAILURE
 *
 ******************************************************************************/
int crc16_gen(uint8_t *buffPtr, uint32_t dataLen, uint16_t poly, uint16_t *crcVal)
{
	uint16_t crc = CRC16_INIT;
	const uint16_t *crc_lut = NULL;
	switch (poly)
	{
#ifdef __CRC_LSB
	case 0x8005:
		crc_lut = crc16_8005_lsb_lut;
		break;
	case 0x1021:
		crc_lut = crc16_1021_lsb_lut;
		break;
	default:
		return FAILURE;
#else
	case 0x8005:
		crc_lut = crc16_8005_msb_lut;
		break;
	case 0x1021:
		crc_lut = crc16_1021_msb_lut;
		break;
	default:
		return FAILURE;
#endif
	}
	for (int i = 0; i < dataLen; i++)
	{
#ifdef __CRC_LSB
		crc = (crc >> 8) ^ crc_lut[(uint8_t)(crc ^ buffPtr[i])];
#else
		crc = (crc << 8) ^ crc_lut[(uint8_t)((crc >> 8) ^ buffPtr[i])];
#endif
	}
	*crcVal = crc;
	return SUCCESS;
}

